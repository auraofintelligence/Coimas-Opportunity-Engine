import assert from "node:assert/strict";
import {readFile} from "node:fs/promises";
import {normalise,evaluate,inScope,validatePortfolio,buildDataset} from "./engine.mjs";
const today="2026-11-24",portfolio=JSON.parse(await readFile(new URL("./data/portfolio.json",import.meta.url),"utf8"));
const refs=[...new Map(portfolio.projects.flatMap(p=>p.sourceRepos).map(r=>[r.name,{name:r.name,repositoryUrl:r.url}])).values()];
assert.equal(validatePortfolio(portfolio,{projects:refs}),true);
const p=portfolio.projects.find(x=>x.id==="founder-mobility"),path=p.pathways[0];
const j={id:"ee",name:"Estonia",records:{"digital-residency":normalise({status:"mapped",checked:today,confidence:"search snapshot",sources:[{url:"https://example.org"}]},"digital-residency",today)}};
const base=evaluate(p,path,j,portfolio.scopes,[],{},today);
assert.equal(base.fit,null);assert.equal(base.gateState,"unresolved");assert.equal(base.rankable,false);
const observation=c=>({projectId:p.id,pathway:path.id,placeId:j.id,requirementId:c.id,reviewed:true,result:"met",source:"https://example.org",note:"Fixture only",checked:today});
const all=path.criteria.map(observation);
assert.equal(evaluate(p,path,j,portfolio.scopes,all,{},today).fit,100);
assert.equal(evaluate(p,path,j,portfolio.scopes,all,{},today).rankable,true);
const blocked=all.map((o,i)=>i?o:{...o,result:"not-met"});
assert.equal(evaluate(p,path,j,portfolio.scopes,blocked,{},today).gateState,"blocked");
assert.equal(evaluate(p,path,j,portfolio.scopes,[...all,{...all[0],result:"not-met"}],{},today).rankable,false);
assert.equal(evaluate(p,path,j,portfolio.scopes,all.map(o=>({...o,checked:"2025-01-01"})),{},today).fit,null);
const regional=portfolio.projects.find(x=>x.id==="oceania-wellbeing").pathways[0];
assert.equal(inScope(regional,j,portfolio.scopes),false);assert.equal(inScope(regional,{id:"fj"},portfolio.scopes),true);
assert.equal(evaluate(p,path,j,portfolio.scopes,[],{[path.criteria[0].id]:0},today).gateState,"unresolved");
const d=buildDataset(portfolio,{projects:refs},{places:[{id:"ee",name:"Estonia"}]}, {},{},today);
assert.equal(d.places[0].records["digital-residency"].status,"unknown");
console.log("PASS: curated profiles, relevant pathways, geographic scope, unreviewed and contradictory evidence, non-bypassable gates, stale records.");
